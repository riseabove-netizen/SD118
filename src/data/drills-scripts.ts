export function slugifyDrill(label: string): string {
  return label
    .toLowerCase()
    .replace(/[\(\)\[\]\{\}\.,;:!\?]/g, '')
    .trim()
    .replace(/\s+/g, '-')
}

export function findDrillScript(slug: string | null | undefined): DrillScript | null {
  if (!slug) return null
  const norm = slug.toLowerCase()
  return DRILL_SCRIPTS.find(d => d.slug === norm) ||
         DRILL_SCRIPTS.find(d => slugifyDrill(d.title) === norm) ||
         null
}
